// The provisioning surface. Users left the config file because that file grew with the organisation
// while the thing worth reviewing in git — the set of access rules — did not. What is here is the
// replacement, and it is deliberately small: create, read, update, delete, and set attributes.
//
// Every route is admin-only and every mutation is audited. Setting an attribute is the single most
// privilege-relevant call in the product: whoever sets tenant_id decides what a caller sees, which
// is why the audit row carries the values and not just the fact of the change.

// decode reads a JSON body under a size cap, so a malformed or hostile request cannot cost memory.
func decode(w http.ResponseWriter, r *http.Request, v any) bool {
	return decodeBody(w, r, v, false)
}

// decodeOptional is decode for a request whose body may legitimately be absent.
//
// It exists because "is there a body" cannot be answered by Content-Length: a chunked request
// reports -1, so testing for a positive length silently skips a body that was in fact sent. Ask the
// decoder instead.
func decodeOptional(w http.ResponseWriter, r *http.Request, v any) bool {
	return decodeBody(w, r, v, true)
}

func decodeBody(w http.ResponseWriter, r *http.Request, v any, optional bool) bool {
	dec := json.NewDecoder(http.MaxBytesReader(w, r.Body, 64<<10))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		if optional && errors.Is(err, io.EOF) {
			return true
		}
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": "malformed request: " + err.Error()})
		return false
	}
	return true
}

// storeErr maps a provisioning error to a status code. A script acting on 404 when it should act on
// 409 misprovisions silently, so the distinction is worth keeping.
func storeErr(w http.ResponseWriter, err error) {
	switch {
	case errors.Is(err, store.ErrNotFound):
		writeJSON(w, http.StatusNotFound, map[string]any{"error": err.Error()})
	case errors.Is(err, store.ErrExists), errors.Is(err, store.ErrModelConflict):
		writeJSON(w, http.StatusConflict, map[string]any{"error": err.Error()})
	case errors.Is(err, store.ErrUnknownRole), errors.Is(err, auth.ErrInvalidHash):
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": err.Error()})
	case errors.Is(err, store.ErrProtected):
		writeJSON(w, http.StatusForbidden, map[string]any{"error": err.Error()})
	default:
		writeJSON(w, http.StatusInternalServerError, map[string]any{"error": "could not complete request"})
	}
}

// checkAttrs keeps attribute names usable as user.<name> policy references. Valid names are added
// to the policy vocabulary by the same transaction that stores their first value.
func checkAttrs(w http.ResponseWriter, keys []string) bool {
	var bad []string
	for _, k := range keys {
		if !schema.ValidIdent(k) {
			bad = append(bad, k)
		}
	}
	if len(bad) > 0 {
		sort.Strings(bad)
		writeJSON(w, http.StatusBadRequest, map[string]any{
			"error": "attribute names must be plain identifiers: " + strings.Join(bad, ", "),
		})
		return false
	}
	return true
}

// Imported hashes must use the bounded canonical profile generated by `lightship hash`.
func checkHash(w http.ResponseWriter, hash string) bool {
	if hash != "" && auth.ValidateHash(hash) != nil {
		writeJSON(w, http.StatusBadRequest, map[string]any{
			"error": "password_hash must use the Argon2id profile generated by `lightship hash`"})
		return false
	}
	return true
}

