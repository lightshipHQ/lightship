// createUser provisions a user and, unless the caller supplied a hash, the password itself.
//
// Generating it here is what stops an admin knowing every user's password forever. The old shape —
// the admin runs `lightship hash` and posts the result — meant the person who provisioned an
// account could sign in as its owner indefinitely, and every audit row that session wrote named the
// wrong actor. Now the admin reads a generated password once, hands it over, and the flag below
// makes it useless the moment it has been used: this is the Gitea and Forgejo shape, and it is the
// only version of provisioning that the audit log's central claim survives.
//
// The password travels outbound exactly once, in this response, and only its argon2id hash is
// stored — the same handling an API key token gets. That is not the boundary `password_hash`
// protects, which is about plaintext arriving *inbound* from an admin who would then know it.
func (s *Server) createUser(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Username     string            `json:"username"`
		PasswordHash string            `json:"password_hash"`
		Attributes   map[string]string `json:"attributes"`
		Roles        []string          `json:"roles"`
		// A pointer so that omitting it means the default rather than false. The default is true,
		// because the common case is a person being enrolled and the expensive mistake is a shared
		// password nobody is ever forced to replace.
		MustChangePassword *bool `json:"must_change_password"`
	}
	if !decode(w, r, &body) {
		return
	}
	if body.Username == "" {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": "username is required"})
		return
	}
	if !checkHash(w, body.PasswordHash) || !checkAttrs(w, keys(body.Attributes)) {
		return
	}
	mustChange := body.MustChangePassword == nil || *body.MustChangePassword

	// No hash supplied: generate the credential rather than leave the account unusable. The
	// generator is the bootstrap admin's, because the two credentials are handed over the same way
	// and should be the same string.
	hash, generated := body.PasswordHash, ""
	if hash == "" {
		pw, err := store.GeneratePassword()
		if err != nil {
			writeJSON(w, http.StatusInternalServerError,
				map[string]any{"error": "could not generate a password"})
			return
		}
		h, err := auth.Hash(pw)
		if err != nil {
			writeJSON(w, http.StatusInternalServerError,
				map[string]any{"error": "could not generate a password"})
			return
		}
		hash, generated = h, pw
	}

	if err := s.st.CreateUser(r.Context(), body.Username, hash,
		body.Attributes, body.Roles, mustChange); err != nil {
		storeErr(w, err)
		return
	}
	// The audit row records that a password was generated and that the user must change it, never
	// the password. What an operator needs to reconstruct later is who was enrolled on what terms.
	s.audit(r, "user.create", "", map[string]any{
		"username": body.Username, "roles": body.Roles, "attributes": body.Attributes,
		"password_generated": generated != "", "must_change_password": mustChange})
	out := map[string]any{"username": body.Username}
	if generated != "" {
		// The only time this password is readable. Only its argon2id hash is stored, so an admin
		// who loses it reprovisions rather than recovers it.
		out["password"] = generated
	}
	writeJSON(w, http.StatusCreated, out)
}

func (s *Server) listUsers(w http.ResponseWriter, r *http.Request) {
	users, err := s.st.ListUsers(r.Context())
	if err != nil {
		storeErr(w, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"users": users})
}

func (s *Server) getUser(w http.ResponseWriter, r *http.Request) {
	u, err := s.st.GetUser(r.Context(), r.PathValue("username"))
	if err != nil {
		storeErr(w, err)
		return
	}
	writeJSON(w, http.StatusOK, u)
}

// updateUser sets password and roles. Both fields are pointers so that omitting one leaves it
// alone, while sending an empty roles list genuinely removes every role — the supported way to
// suspend a caller without deleting the audit history attached to their name.
func (s *Server) updateUser(w http.ResponseWriter, r *http.Request) {
	var body struct {
		PasswordHash *string   `json:"password_hash"`
		Roles        *[]string `json:"roles"`
	}
	if !decode(w, r, &body) {
		return
	}
	if body.PasswordHash != nil && !checkHash(w, *body.PasswordHash) {
		return
	}
	username := r.PathValue("username")
	revoked, err := s.st.UpdateUser(r.Context(), username, body.PasswordHash, body.Roles)
	if err != nil {
		storeErr(w, err)
		return
	}
	detail := map[string]any{"username": username}
	if body.Roles != nil {
		detail["roles"] = *body.Roles
	}
	if body.PasswordHash != nil {
		detail["password_changed"] = true
		detail["sessions_revoked"] = revoked
	}
	s.audit(r, "user.update", "", detail)
	out := map[string]any{"username": username}
	if body.PasswordHash != nil {
		out["sessions_revoked"] = revoked
	}
	writeJSON(w, http.StatusOK, out)
}

func (s *Server) deleteUser(w http.ResponseWriter, r *http.Request) {
	username := r.PathValue("username")
	if err := s.st.DeleteUser(r.Context(), username); err != nil {
		storeErr(w, err)
		return
	}
	// Sessions and keys cascade with the row, so this is revocation and not a request to expire.
	s.audit(r, "user.delete", "", map[string]any{"username": username})
	writeJSON(w, http.StatusOK, map[string]any{"deleted": username})
}

// patchAttributes updates the attributes named in the body and leaves the rest alone, with an
// explicit null removing one — JSON Merge Patch semantics. Removal has to be expressible: an
// attribute that could only ever be set would be a grant nobody could narrow.
//
// There is deliberately no whole-set replace beside it. Two ways to write the most
// privilege-relevant field in the product is one more than the number of behaviours worth
// reasoning about, and a replace sent with a key accidentally omitted silently revokes it.
func (s *Server) patchAttributes(w http.ResponseWriter, r *http.Request) {
	var attrs map[string]*string
	if !decode(w, r, &attrs) {
		return
	}
	if len(attrs) == 0 {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": "no attributes given"})
		return
	}
	if !checkAttrs(w, keys(attrs)) {
		return
	}
	username := r.PathValue("username")
	before, err := s.st.GetUser(r.Context(), username)
	if err != nil {
		storeErr(w, err)
		return
	}
	after, err := s.st.PatchAttributes(r.Context(), username, attrs)
	if err != nil {
		storeErr(w, err)
		return
	}
	// Before and after in full, not the patch: this call decides what rows the user can see, and a
	// delta is not enough to reconstruct who could see what, when.
	s.audit(r, "attribute.set", "", map[string]any{
		"username": username, "before": before.Attributes, "after": after})
	writeJSON(w, http.StatusOK, map[string]any{"username": username, "attributes": after})
}

// keys is the set of names a request wants to touch, whatever the value type carrying them.
func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}

