// createKey is the one route on this file open to every caller, because a key is how the API and an
// MCP client are reached and a product consumed that way cannot make every user ask an admin for a
// credential.
//
// A key is always minted for the authenticated caller, never for anyone else. Minting on behalf of
// another principal would be a silent impersonation primitive: every audit row such a key writes
// names the target user, so an admin could act as anyone with nothing in the log to show it — the
// exact failure the audit trail exists to rule out. Onboarding therefore runs the other way: an
// admin creates the user, and the user signs in and mints their own key. Self-service escalates
// nothing, because a key grants exactly what its user's roles grant, resolved fresh on every
// request.
func (s *Server) createKey(w http.ResponseWriter, r *http.Request) {
	var body struct {
		Name      string `json:"name"`
		ExpiresIn string `json:"expires_in"`
	}
	if !decode(w, r, &body) {
		return
	}
	if body.Name == "" {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": "name is required"})
		return
	}

	sess := sessionFrom(r.Context())
	expires, err := keyExpiry(body.ExpiresIn, s.keyExpiry, time.Now())
	if err != nil {
		writeJSON(w, http.StatusBadRequest, map[string]any{"error": err.Error()})
		return
	}

	token, err := auth.NewKey()
	if err != nil {
		writeJSON(w, http.StatusInternalServerError, map[string]any{"error": "could not mint key"})
		return
	}
	id, err := s.st.CreateKey(r.Context(), body.Name, token, sess.Username, expires)
	if err != nil {
		storeErr(w, err)
		return
	}
	s.audit(r, "key.create", "", map[string]any{"key_id": id, "name": body.Name})
	// The only time the token is ever readable. Only its sha256 is stored.
	writeJSON(w, http.StatusCreated, map[string]any{
		"id": id, "name": body.Name, "username": sess.Username, "token": token})
}

type keyExpiryPolicy struct {
	Default time.Duration
	Maximum time.Duration
}

func keyExpiry(expiresIn string, policy keyExpiryPolicy, now time.Time) (*time.Time, error) {
	if expiresIn == "" && policy.Default > 0 {
		expiresIn = policy.Default.String()
	}
	if expiresIn == "" {
		return nil, nil
	}
	d, err := time.ParseDuration(expiresIn)
	if err != nil || d <= 0 {
		return nil, errors.New("expires_in must be a positive Go duration, e.g. \"720h\"")
	}
	if policy.Maximum > 0 && d > policy.Maximum {
		return nil, fmt.Errorf("API keys may live for at most %s", policy.Maximum)
	}
	t := now.Add(d)
	return &t, nil
}

// listKeys shows a caller their own keys, and an admin every key.
func (s *Server) listKeys(w http.ResponseWriter, r *http.Request) {
	keys, err := s.st.ListKeys(r.Context(), scope(r))
	if err != nil {
		storeErr(w, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"keys": keys})
}

// scope is the username a non-admin caller is confined to, and empty for an admin.
func scope(r *http.Request) string {
	sess := sessionFrom(r.Context())
	if sess.IsAdmin() {
		return ""
	}
	return sess.Username
}

func (s *Server) revokeKey(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	if err := s.st.RevokeKey(r.Context(), id, scope(r)); err != nil {
		storeErr(w, err)
		return
	}
	s.audit(r, "key.revoke", "", map[string]any{"key_id": id})
	writeJSON(w, http.StatusOK, map[string]any{"revoked": id})
}
